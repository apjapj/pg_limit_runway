#!/usr/bin/env bash
# s4: a parent key widened to bigint, a child foreign key still int4. Every check on the parent's
# sequence says there is plenty left, and the child cannot reference any parent past 2,147,483,647.
. "$(dirname "$0")/lib.sh"
setup_schema
psql_q -c "CREATE TABLE $SCHEMA.s4_customers (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text)" \
       -c "CREATE TABLE $SCHEMA.s4_orders (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            customer_id int4 REFERENCES $SCHEMA.s4_customers (id))" \
       -c "SELECT setval(pg_get_serial_sequence('$SCHEMA.s4_customers', 'id'), 2147483647)" \
       -c "INSERT INTO $SCHEMA.s4_customers (name) VALUES ('first past 2^31')" >/dev/null

say "the usual check (pg_sequences, on the parent)"
psql -X -P pager=off -c "
SELECT sequencename, data_type, last_value, round(100.0 * last_value / max_value, 6) AS pct_used
  FROM pg_sequences WHERE schemaname = '$SCHEMA' AND sequencename LIKE 's4_customers%'"

say "what actually happens: an order for that customer"
err=$(try_sql "INSERT INTO $SCHEMA.s4_orders (customer_id) SELECT max(id) FROM $SCHEMA.s4_customers")
note "${err:-(no error)}"

say "evidence: the foreign key's two column types (pg_constraint)"
psql -X -P pager=off -c "
SELECT con.conname, format_type(ca.atttypid, ca.atttypmod) AS child_col_type,
       format_type(pa.atttypid, pa.atttypmod) AS parent_col_type
  FROM pg_constraint con
  JOIN pg_attribute ca ON ca.attrelid = con.conrelid AND ca.attnum = con.conkey[1]
  JOIN pg_attribute pa ON pa.attrelid = con.confrelid AND pa.attnum = con.confkey[1]
 WHERE con.contype = 'f' AND con.conrelid = '$SCHEMA.s4_orders'::regclass"

say "checks"
assert_true "the parent's sequence is under 0.001% used" "$(val "SELECT 100.0 * last_value / max_value < 0.001 FROM pg_sequences WHERE sequencename LIKE 's4_customers%'")"
assert_true "an order for the newest customer fails with integer out of range" "$([[ "$err" == *"integer out of range"* ]] && echo t || echo f)"
finding "lr_scen.s4_%"
assert_finding lr_scen.s4_orders.customer_id exhausted '%s4_customers.id is bigint%' '' '%past 2147483647%' 1
say "the command the Act stage builds (limit_runway_command)"
if use_extension; then
    while IFS= read -r line; do note "$line"; done \
        < <(val "SELECT tier || ' | ' || command FROM limit_runway_command(0)
                   WHERE object = '$SCHEMA.s4_orders.customer_id'")
else
    note "pg_limit_runway is not installed on this server; command not checked"
fi
say "expected finding"
note "s4_orders.customer_id (int4) references s4_customers.id (bigint), which is already past 2147483647:"
note "new customers can no longer be referenced. A limit on the child column, reached through the parent."
