#!/usr/bin/env bash
# s20: a composite foreign key, one pair int4 -> bigint. The pair is invisible to a check that reads
# conkey[1]/confkey[1], which is what 0.5.1 did: the child column cannot hold the parent's next value,
# and no finding named it. 0.5.2 reads the key pair by pair.
. "$(dirname "$0")/lib.sh"
setup_schema
psql_q -c "CREATE TABLE $SCHEMA.s20_p (a bigint GENERATED BY DEFAULT AS IDENTITY, b int4,
                                            PRIMARY KEY (a, b))" \
       -c "CREATE TABLE $SCHEMA.s20_c (a int4, b int4,
                                           FOREIGN KEY (a, b) REFERENCES $SCHEMA.s20_p (a, b))" \
       -c "SELECT setval(pg_get_serial_sequence('$SCHEMA.s20_p', 'a'), 2147483647)" \
       -c "INSERT INTO $SCHEMA.s20_p (b) VALUES (1)" >/dev/null

say "the usual check (pg_sequences, on the parent's first column)"
psql -X -P pager=off -c "
SELECT sequencename, data_type, last_value, round(100.0 * last_value / max_value, 6) AS pct_used
  FROM pg_sequences WHERE schemaname = '$SCHEMA' AND sequencename LIKE 's20_p%'"

say "what actually happens: a child row for that parent"
err=$(try_sql "INSERT INTO $SCHEMA.s20_c (a, b) SELECT a, b FROM $SCHEMA.s20_p")
note "${err:-(no error)}"

say "evidence: the composite key's column pairs and their types"
psql -X -P pager=off -c "
SELECT con.conname, k.ord, ca.attname AS child_col, format_type(ca.atttypid, ca.atttypmod) AS child_type,
       pa.attname AS parent_col, format_type(pa.atttypid, pa.atttypmod) AS parent_type
  FROM pg_constraint con
  JOIN LATERAL unnest(con.conkey, con.confkey) WITH ORDINALITY AS k(ca, pa, ord) ON true
  JOIN pg_attribute ca ON ca.attrelid = con.conrelid AND ca.attnum = k.ca
  JOIN pg_attribute pa ON pa.attrelid = con.confrelid AND pa.attnum = k.pa
 WHERE con.contype = 'f' AND con.conrelid = '$SCHEMA.s20_c'::regclass
 ORDER BY k.ord"

say "checks"
assert_true "the parent's sequence is under 0.001% used" "$(val "SELECT 100.0 * last_value / max_value < 0.001 FROM pg_sequences WHERE sequencename LIKE 's20_p%'")"
assert_true "a child row for the newest parent fails with integer out of range" "$([[ "$err" == *"integer out of range"* ]] && echo t || echo f)"
finding "lr_scen.s20_%"
assert_finding lr_scen.s20_c.a exhausted '%s20_p.a is bigint%' '' '%past 2147483647%' 1

say "the command the Act stage builds (limit_runway_command)"
if use_extension; then
    cmd=$(val "SELECT command FROM limit_runway_command(0) WHERE object = '$SCHEMA.s20_c.a'")
    note "$cmd"
    psql_q -c "$cmd"
    err2=$(try_sql "INSERT INTO $SCHEMA.s20_c (a, b) SELECT a, b FROM $SCHEMA.s20_p")
    assert_true "after the command, the same child row is accepted" "$([[ -z "$err2" ]] && echo t || echo f)"
else
    note "pg_limit_runway is not installed on this server; command not checked"
fi

say "expected finding"
note "s20_c.a (int4) is one column of a composite foreign key whose parent column s20_p.a is bigint."
note "The sequence's own percentage says there is room; the child column has none."
