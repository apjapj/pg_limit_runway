-- test/01_limit_runway.sql: the objects, their shape, the grants, and the sequence rules on fixtures built
-- here.
--
-- The scenario suite (scenarios/run.sh) checks each finding against a real fixture on 14 and 18; this
-- file pins what a scenario does not: the columns, that nothing writes, that nothing is open to PUBLIC,
-- what a role without grants and a role without privileges get, and the invariants a pager depends on.
-- Every check filters to objects made here, or holds for any row, so other objects on the server cannot
-- turn it red. All of it runs in one transaction and is rolled back.
\set ON_ERROR_STOP 1
\set QUIET 1
\o /dev/null
SET client_min_messages = warning;
BEGIN;
CREATE EXTENSION IF NOT EXISTS pgtap;
CREATE EXTENSION IF NOT EXISTS pg_limit_runway;
\o
SELECT plan(33);

SELECT has_view('limit_runway', 'the limit_runway view exists');
SELECT has_function('limit_runway_findings', ARRAY['numeric', 'interval'], 'limit_runway_findings(numeric, interval) exists');
SELECT has_function('limit_runway_text', ARRAY['numeric', 'interval'], 'limit_runway_text(numeric, interval) exists');
SELECT columns_are('limit_runway',
  ARRAY['rank_class', 'rank_label', 'kind', 'object', 'current_value', 'limit_value', 'used_fraction',
        'until_date', 'state', 'detail', 'then', 'unknowns'],
  'limit_runway has the columns docs/ranking.md describes, including state, then and unknowns');
SELECT is((SELECT count(*)::int FROM pg_proc p JOIN pg_depend d ON d.objid = p.oid
            JOIN pg_extension e ON e.oid = d.refobjid AND e.extname = 'pg_limit_runway'
           WHERE p.provolatile = 'v' OR p.prosecdef), 0,
          'no function in the extension is VOLATILE or SECURITY DEFINER: it reads, with the caller''s rights');

-- ---------------------------------------------------------------- fixtures
\o /dev/null
CREATE SCHEMA lr_test;
-- s1's trap: a bigint sequence on an int4 column, standing past the column's maximum.
CREATE SEQUENCE lr_test.past_seq AS bigint;
CREATE TABLE lr_test.past (id int4 PRIMARY KEY DEFAULT nextval('lr_test.past_seq'));
ALTER SEQUENCE lr_test.past_seq OWNED BY lr_test.past.id;
SELECT setval('lr_test.past_seq', 2147483648);
-- s12's trap: explicit ids, a sequence never advanced.
CREATE TABLE lr_test.behind (id serial PRIMARY KEY);
INSERT INTO lr_test.behind SELECT generate_series(1, 5);
-- The same, with no index on the column: the tool may not scan, so it cannot say.
CREATE TABLE lr_test.noindex (id serial, v int);
INSERT INTO lr_test.noindex (id) SELECT generate_series(1, 5);
-- Close but not reached: an int2 identity with 7 values left.
CREATE TABLE lr_test.close (id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
SELECT setval(pg_get_serial_sequence('lr_test.close', 'id'), 32760);
-- A partition whose last bound is past, with a DEFAULT holding a row for the present.
CREATE TABLE lr_test.events (at timestamptz NOT NULL) PARTITION BY RANGE (at);
CREATE TABLE lr_test.events_old PARTITION OF lr_test.events FOR VALUES FROM ('2000-01-01') TO ('2000-02-01');
CREATE TABLE lr_test.events_default PARTITION OF lr_test.events DEFAULT;
INSERT INTO lr_test.events VALUES (now());
-- An expired password.
CREATE ROLE lr_test_expired LOGIN VALID UNTIL '2000-01-01';
-- A role with no grants, and a monitoring role with the grants INSTALL.md lists but no superuser and no
-- SELECT on the tables.
CREATE ROLE lr_test_nogrant;
CREATE ROLE lr_test_nostats;
GRANT EXECUTE ON FUNCTION limit_runway_findings(numeric, interval) TO lr_test_nostats;
CREATE ROLE lr_test_monitor;
GRANT pg_monitor TO lr_test_monitor;
GRANT SELECT ON limit_runway TO lr_test_monitor;
GRANT EXECUTE ON FUNCTION limit_runway_findings(numeric, interval), limit_runway_text(numeric, interval) TO lr_test_monitor;
GRANT USAGE ON SCHEMA lr_test TO lr_test_monitor;
GRANT SELECT ON SEQUENCE lr_test.behind_id_seq TO lr_test_monitor;
CREATE TEMP TABLE f AS SELECT * FROM limit_runway_findings();
\o

-- ---------------------------------------------------------------- the serial finding is a state
SELECT is((SELECT state FROM f WHERE object = 'lr_test.past.id'), 'exhausted',
          'a sequence past its column''s maximum is exhausted');
SELECT is((SELECT used_fraction FROM f WHERE object = 'lr_test.past.id'), NULL,
          'and carries no percentage: exhausted is a state, not 100% or more');
SELECT ok((SELECT detail FROM f WHERE object = 'lr_test.past.id') LIKE '%stands past it at 2147483648%',
          'and says the sequence stands past the limit, rather than reporting -1 values left');
SELECT is((SELECT limit_value FROM f WHERE object = 'lr_test.past.id'), 2147483647::numeric,
          'the limit is the int4 column''s, found through pg_depend, not the bigint sequence''s');

SELECT is((SELECT state FROM f WHERE object = 'lr_test.behind.id'), 'behind the data',
          'a sequence behind its data is reported as that state');
SELECT is((SELECT rank_class FROM f WHERE object = 'lr_test.behind.id'), 1, 'and as failing now');
SELECT is((SELECT used_fraction FROM f WHERE object = 'lr_test.behind.id'), NULL,
          'with no percentage: the usual check would say 500%');
SELECT ok((SELECT detail FROM f WHERE object = 'lr_test.behind.id') LIKE '%Fix, to run by hand: SELECT setval(''lr_test.behind_id_seq'', 5)',
          'and names the setval to run by hand');

SELECT is((SELECT state FROM f WHERE object = 'lr_test.noindex.id'), 'not established',
          'with no index leading with the column, behind-the-data is not established');
SELECT ok((SELECT unknowns[1] FROM f WHERE object = 'lr_test.noindex.id') LIKE '%no btree index leads with id, and the table is not scanned',
          'and the note says why: the table is not scanned');

SELECT is((SELECT state || ' ' || rank_class FROM f WHERE object = 'lr_test.close.id'), 'no rate yet 3',
          'an int2 identity with 7 values left is "no rate yet", class 3');
SELECT ok((SELECT detail FROM f WHERE object = 'lr_test.close.id') LIKE '7 of 32767 values left%',
          'counting values left, never a projected date in 0.1');

-- Invariants a pager depends on, over every row the server produces, not only the fixtures.
SELECT is((SELECT count(*)::int FROM f WHERE used_fraction < 0 OR used_fraction > 1), 0,
          'no row anywhere has a share used below 0 or above 1');
SELECT is((SELECT count(*)::int FROM f WHERE detail ~ '(^|[^0-9])-[0-9]+ (of|values)'), 0,
          'no row anywhere reports a negative count of values');
SELECT is((SELECT count(*)::int FROM f WHERE until_date IS NOT NULL AND kind = 'sequence'), 0,
          'no sequence has a date: 0.1 has no history, so no rate');

-- ---------------------------------------------------------------- the secondary lines
SELECT ok((SELECT "then"[1] FROM f WHERE object = 'lr_test.events') LIKE '%DEFAULT lr_test.events_default holds rows%cannot be created until they are moved',
          'a reached partition with rows in its DEFAULT says the DEFAULT blocks the fix');
SELECT ok((SELECT state || ' ' || rank_class || ' ' || "then"[1] FROM f WHERE object = 'role lr_test_expired')
          LIKE 'expired 1 logins that do not use a password are not affected%',
          'an expired password is failing now, and says only password logins are refused');

-- ---------------------------------------------------------------- order
SELECT is((SELECT count(*)::int FROM (SELECT rank_class, lag(rank_class) OVER () AS prev FROM limit_runway) v
            WHERE rank_class < prev), 0,
          'the view lists every failing-now row before any dated, no-rate or peak row');

-- ---------------------------------------------------------------- grants
SELECT is((SELECT count(*)::int FROM pg_proc p JOIN pg_depend d ON d.objid = p.oid
            JOIN pg_extension e ON e.oid = d.refobjid AND e.extname = 'pg_limit_runway'
           WHERE has_function_privilege('lr_test_nogrant', p.oid, 'EXECUTE')), 0,
          'no function is executable by a role with no grants: closed by default');
SET ROLE lr_test_nogrant;
SELECT throws_ok('SELECT * FROM limit_runway_text()', '42501', NULL, 'a role with no grants is refused');
RESET ROLE;

SET ROLE lr_test_monitor;
\o /dev/null
CREATE TEMP TABLE fm AS SELECT * FROM limit_runway_findings();
\o
SELECT lives_ok('SELECT * FROM limit_runway', 'a monitoring role with the INSTALL.md grants reads the view');
SELECT ok((SELECT unknowns[1] FROM fm WHERE object = 'member space') LIKE '%needs superuser%',
          'without superuser, MultiXact member space is not established, and says so');
SELECT ok((SELECT detail FROM fm WHERE kind = 'sequence' AND object LIKE '% column(s) this role cannot read')
           LIKE '%lr_test.behind.id%',
          'a table it cannot read is listed as not established, not passed over as fine');
SELECT ok((SELECT detail FROM fm WHERE object LIKE '% sequence(s) this role cannot read')
           LIKE '%lr_test.past_seq%',
          'sequences it cannot read are one not-established row naming them, not one row each');
RESET ROLE;
SELECT is((SELECT unknowns FROM f WHERE object = 'member space') IS NOT NULL
           AND (SELECT detail FROM f WHERE object = 'member space') LIKE '%member segment file(s)%', true,
          'as superuser the member segment files are counted, and the limit is still not established in 0.1');

SELECT is((SELECT count(*)::int FROM fm WHERE kind = 'connections' AND state = 'not established'), 0,
          'with pg_monitor, which includes pg_read_all_stats, connection counts are not marked as a gap');
SET ROLE lr_test_nostats;
SELECT ok((SELECT unknowns[1] FROM limit_runway_findings() WHERE kind = 'connections') LIKE '%without pg_read_all_stats%',
          'with the grants but without pg_read_all_stats, connections are not established, not counted low');
SELECT is((SELECT count(*)::int FROM limit_runway_findings() WHERE kind = 'connections'), 1,
          'and that one row replaces the counts: none is reported from what the role cannot see');
RESET ROLE;

SELECT * FROM finish();
ROLLBACK;
